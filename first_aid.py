def get_topic(key: str) -> dict[str, Any] | None:
    t = TOPICS.get(key)
    if not t:
        return None
    out = dict(t)
    out["key"] = key
    out["emergency_line"] = EMERGENCY_LINE
    out["disclaimer"] = "آموزش عمومی اولیا؛ در همه‌ی موارد با اورژانس هماهنگ باش. "+ EMERGENCY_LINE
    return out


def list_topics() -> list[dict[str, str]]:
    return [{"key": k, "title": v["title"]} for k, v in TOPICS.items()]


def cpr_timing() -> dict[str, Any]:
    """اطلاعات مترونوم برای UI (وب/دسکتاپ): هر فشار حدود 0.545 ثانیه."""
    interval = 60.0 / CPR_BPM
    return {"bpm": CPR_BPM, "interval_sec": round(interval, 3), "depth_cm": "۵–۶ سانتی‌متر", "ratio": "30:2",
            "emergency_line": EMERGENCY_LINE}
